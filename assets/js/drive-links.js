(function () {
  function init() {
    document.querySelectorAll('[data-drive-key]').forEach(function (a) {
      var parts=a.dataset.driveKey.split('/');
      var area=window.BSESS_DRIVE_LINKS[parts[0]] || {};
      var entry=area[parts[1]] || {};
      var raw=String(entry[parts[2] || 'url'] || '').trim();
      a.addEventListener('click',function(e){if(a.getAttribute('aria-disabled')==='true') e.preventDefault();});
      if (!raw) return;
      try {
        var u=new URL(raw);
        if(u.protocol!=='https:' || !['drive.google.com','docs.google.com'].includes(u.hostname)) throw new Error('Use an HTTPS Google Drive or Google Docs share URL');
        a.href=u.href; a.target='_blank'; a.rel='noopener noreferrer';
        a.removeAttribute('aria-disabled');a.removeAttribute('role');a.removeAttribute('tabindex');
        a.title='Open Google Drive evidence';
      } catch(e) {console.warn('[BSESS] Invalid Drive URL for '+a.dataset.driveKey,e.message);}
    });
  }
  if(document.readyState==='loading') document.addEventListener('DOMContentLoaded',init); else init();
})();
